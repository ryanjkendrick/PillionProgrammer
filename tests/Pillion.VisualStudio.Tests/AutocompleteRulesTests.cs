public sealed class SuppressionRulesTests
{
    private static readonly AutocompleteSettings Enabled = AutocompleteSettings.Default;

    [Theory]
    [InlineData(@"C:\src\Form1.Designer.cs", true)]
    [InlineData(@"C:\src\obj\Debug\App.g.cs", true)]
    [InlineData(@"C:\src\obj\Debug\MainWindow.g.i.cs", true)]
    [InlineData(@"C:\src\wwwroot\lib\jquery.min.js", true)]
    [InlineData(@"C:\src\Resources.designer.vb", true)]
    [InlineData(@"C:\src\Program.cs", false)]
    [InlineData(@"C:\src\site.js", false)]
    [InlineData(@"C:\src\Designer.cs", false)]
    [InlineData("", false)]
    public void GeneratedFileNames_AreRecognised(string path, bool expected)
    {
        Assert.Equal(expected, SuppressionRules.IsGeneratedFileName(path));
    }

    [Theory]
    [InlineData("//------------------------------------------------------------------------------\n// <auto-generated>\n//     This code was generated by a tool.\n// </auto-generated>\nusing System;\n", true)]
    [InlineData("# Code generated by protoc-gen-go. DO NOT EDIT.\npackage foo\n", true)]
    [InlineData("/* @generated */\nexport const x = 1;\n", true)]
    [InlineData("// Copyright (c) Contoso.\nusing System;\nclass AutoGenerated { }\n", false)]
    [InlineData("using System;\n// <auto-generated> is mentioned in line 2 but not as a comment here\n", true)]
    [InlineData("using System;\nvar s = \"<auto-generated>\";\n", false)]
    public void AutoGeneratedHeaders_AreRecognised(string text, bool expected)
    {
        Assert.Equal(expected, SuppressionRules.HasGeneratedHeader(new StringDocumentText(text)));
    }

    [Fact]
    public void HeaderBeyondTheFirstLines_IsIgnored()
    {
        var text = string.Concat(Enumerable.Repeat("int x;\n", SuppressionRules.HeaderLines)) + "// <auto-generated>\n";

        Assert.False(SuppressionRules.HasGeneratedHeader(new StringDocumentText(text)));
    }

    [Fact]
    public void EvaluateDocument_AppliesTheRulesInOrder()
    {
        var small = new StringDocumentText("class C { }\n");
        var big = new StringDocumentText(new string('x', SuppressionRules.MaxDocumentLength + 1));
        var generated = new StringDocumentText("// <auto-generated/>\nclass C { }\n");
        var noPython = new AutocompleteSettings(enabled: true, ["Python"], announceSuggestions: true);
        var off = new AutocompleteSettings(enabled: false, [], announceSuggestions: true);

        Assert.Equal(SuppressionReason.None, SuppressionRules.EvaluateDocument("a.cs", "csharp", small, Enabled));
        Assert.Equal(SuppressionReason.FeatureDisabled, SuppressionRules.EvaluateDocument("a.cs", "csharp", small, off));
        Assert.Equal(SuppressionReason.LanguageDisabled, SuppressionRules.EvaluateDocument("a.py", "python", small, noPython));
        Assert.Equal(SuppressionReason.None, SuppressionRules.EvaluateDocument("a.cs", "csharp", small, noPython));
        Assert.Equal(SuppressionReason.TooLarge, SuppressionRules.EvaluateDocument("a.cs", "csharp", big, Enabled));
        Assert.Equal(SuppressionReason.GeneratedFileName, SuppressionRules.EvaluateDocument("a.g.cs", "csharp", small, Enabled));
        Assert.Equal(SuppressionReason.GeneratedHeader, SuppressionRules.EvaluateDocument("a.cs", "csharp", generated, Enabled));
    }

    [Fact]
    public void DocumentOfExactlyOneMegabyte_IsAllowed()
    {
        var text = new StringDocumentText(new string('x', SuppressionRules.MaxDocumentLength));

        Assert.Equal(SuppressionReason.None, SuppressionRules.EvaluateDocument("a.txt", "plaintext", text, Enabled));
    }

    [Theory]
    [InlineData(null, false)]
    [InlineData("", false)]
    [InlineData("WriteLine", true)]
    public void CompletionListWithASelectedItem_Suppresses(string? selected, bool expected)
    {
        Assert.Equal(expected, SuppressionRules.IsCompletionListSelection(selected));
    }
}

public sealed class LatencyWindowTests
{
    private DateTimeOffset _now = new(2026, 10, 9, 9, 0, 0, TimeSpan.Zero);

    [Fact]
    public void FewSamples_NeverDegrade()
    {
        var window = new LatencyWindow(() => _now);
        for (var i = 0; i < LatencyWindow.MinimumSamples - 1; i++)
        {
            window.Record(TimeSpan.FromSeconds(5));
        }

        Assert.False(window.IsDegraded);
        Assert.Equal(LatencyWindow.NormalDebounce, window.Debounce);
    }

    [Fact]
    public void P95OverOnePointFiveSeconds_Degrades_AndRecoversWhenTheSlowSamplesAge()
    {
        var window = new LatencyWindow(() => _now);
        var changes = new System.Collections.Generic.List<bool>();
        window.DegradedChanged += (_, degraded) => changes.Add(degraded);

        for (var i = 0; i < 18; i++)
        {
            window.Record(TimeSpan.FromMilliseconds(400));
        }

        window.Record(TimeSpan.FromSeconds(2));
        window.Record(TimeSpan.FromSeconds(2));
        Assert.True(window.IsDegraded); // p95 of 20 samples is the 19th: 2 s.
        Assert.Equal(LatencyWindow.DegradedDebounce, window.Debounce);

        _now += TimeSpan.FromMinutes(5) + TimeSpan.FromSeconds(1);
        for (var i = 0; i < 20; i++)
        {
            window.Record(TimeSpan.FromMilliseconds(300));
        }

        Assert.False(window.IsDegraded);
        Assert.Equal([true, false], changes);
    }

    [Fact]
    public void OneSlowOutlier_DoesNotDegrade()
    {
        var window = new LatencyWindow(() => _now);
        window.Record(TimeSpan.FromSeconds(9)); // A cold model load.
        for (var i = 0; i < 30; i++)
        {
            window.Record(TimeSpan.FromMilliseconds(500));
        }

        Assert.False(window.IsDegraded);
    }

    [Fact]
    public void Snapshot_ReportsP50AndP95OverTheWindow()
    {
        var window = new LatencyWindow(() => _now);
        for (var i = 1; i <= 100; i++)
        {
            window.Record(TimeSpan.FromMilliseconds(i * 10));
        }

        var snapshot = window.Snapshot();
        Assert.Equal(100, snapshot.Count);
        Assert.Equal(TimeSpan.FromMilliseconds(500), snapshot.P50);
        Assert.Equal(TimeSpan.FromMilliseconds(950), snapshot.P95);
        Assert.Contains("p50 500 ms, p95 950 ms (100 in 5 min)", snapshot.ToString(), StringComparison.Ordinal);

        _now += TimeSpan.FromMinutes(6);
        Assert.Equal(0, window.Snapshot().Count);
    }
}

public sealed class EditTrackerTests
{
    [Fact]
    public void KeepsTheLastFiveDistinctPlaces_NewestFirst()
    {
        var tracker = new EditTracker();
        for (var line = 0; line < 7; line++)
        {
            tracker.Record(@"C:\src\a.cs", line, "line " + line);
        }

        Assert.Equal(
            [@"C:\src\a.cs:7: line 6", @"C:\src\a.cs:6: line 5", @"C:\src\a.cs:5: line 4", @"C:\src\a.cs:4: line 3", @"C:\src\a.cs:3: line 2"],
            tracker.ToRequestStrings());
    }

    [Fact]
    public void TypingOnOneLine_IsOneEntryWithTheLatestText()
    {
        var tracker = new EditTracker();
        tracker.Record(@"C:\src\a.cs", 3, "    var t");
        tracker.Record(@"C:\src\a.cs", 3, "    var to");
        tracker.Record(@"C:\src\a.cs", 3, "    var tot");

        var edit = Assert.Single(tracker.Snapshot());
        Assert.Equal("var tot", edit.Text);
        Assert.Equal(3, edit.Line);
    }

    [Fact]
    public void ReturningToAnEarlierLine_MovesItToTheFront()
    {
        var tracker = new EditTracker();
        tracker.Record("a.cs", 1, "one");
        tracker.Record("b.cs", 1, "two");
        tracker.Record("A.CS", 1, "one again");

        Assert.Equal(["A.CS:2: one again", "b.cs:2: two"], tracker.ToRequestStrings());
    }

    [Fact]
    public void LongLines_AreClipped_AndUnknownFilesIgnored()
    {
        var tracker = new EditTracker();
        tracker.Record(null, 1, "ignored");
        tracker.Record("a.cs", 1, new string('x', 500));

        Assert.Equal(EditTracker.MaxTextLength, tracker.Snapshot().Single().Text.Length);
    }

    [Fact]
    public void Forget_RemovesAFilesEdits()
    {
        var tracker = new EditTracker();
        tracker.Record("a.cs", 1, "one");
        tracker.Record("b.cs", 1, "two");
        tracker.Forget("a.cs");

        Assert.Equal(["b.cs:2: two"], tracker.ToRequestStrings());
    }
}

public sealed class OpenDocumentTrackerTests
{
    [Fact]
    public void ListsDocumentsMostRecentlyUsedFirst_UntilTheirLastViewCloses()
    {
        var tracker = new OpenDocumentTracker();
        tracker.Opened("a.cs");
        tracker.Opened("b.cs");
        tracker.Opened("c.cs");
        tracker.Activated("a.cs");
        Assert.Equal(["a.cs", "c.cs", "b.cs"], tracker.Snapshot());

        tracker.Opened("a.cs"); // A second view of a.cs.
        tracker.Closed("a.cs");
        Assert.Equal(["a.cs", "c.cs", "b.cs"], tracker.Snapshot());

        tracker.Closed("a.cs");
        tracker.Activated("zzz.cs"); // Never opened: ignored.
        Assert.Equal(["c.cs", "b.cs"], tracker.Snapshot());
    }
}

public sealed class DeclarationHeuristicTests
{
    [Theory]
    [InlineData("    public static int Min(IEnumerable<int> numbers)", "csharp", true)]
    [InlineData("    private async Task<string?> LoadAsync(CancellationToken token)", "csharp", true)]
    [InlineData("public sealed class Calculator", "csharp", true)]
    [InlineData("    public int Count { get; set; }", "csharp", true)]
    [InlineData("namespace Scratch;", "csharp", false)]
    [InlineData("        if (x > 0)", "csharp", false)]
    [InlineData("        foreach (var n in numbers)", "csharp", false)]
    [InlineData("        return Sum(numbers);", "csharp", false)]
    [InlineData("        Console.WriteLine(total);", "csharp", false)]
    [InlineData("        var total = Sum(numbers", "csharp", false)]
    [InlineData("export async function load(url: string): Promise<void> {", "typescript", true)]
    [InlineData("const add = (a: number, b: number) => {", "typescript", true)]
    [InlineData("def area(radius):", "python", true)]
    [InlineData("    async def fetch(self, url):", "python", true)]
    [InlineData("class Shape:", "python", true)]
    [InlineData("    total = 0", "python", false)]
    [InlineData("    Public Function Area(radius As Double) As Double", "vb", true)]
    [InlineData("    End Function", "vb", false)]
    public void LooksLikeDeclaration_RecognisesHeaders(string line, string language, bool expected)
    {
        Assert.Equal(expected, DeclarationHeuristic.LooksLikeDeclaration(line, language));
    }

    [Fact]
    public void FindsTheEnclosingMethod_NotASiblingOrTheType()
    {
        const string Code =
            "public static class Calculator\n" +
            "{\n" +
            "    public static int Sum(int[] numbers)\n" +
            "    {\n" +
            "        return 0;\n" +
            "    }\n" +
            "    \n" +
            "    public static int Max(int[] numbers)\n" +
            "    {\n" +
            "        var best = 0;\n" +
            "        foreach (var n in numbers)\n" +
            "        {\n" +
            "            best = n;\n" +
            "        }\n" +
            "    }\n" +
            "}\n";
        var text = new StringDocumentText(Code);

        Assert.Equal("public static int Max(int[] numbers)", DeclarationHeuristic.FindEnclosingDeclaration(text, Code.IndexOf("best = n;", StringComparison.Ordinal), "csharp"));
        Assert.Equal("public static int Sum(int[] numbers)", DeclarationHeuristic.FindEnclosingDeclaration(text, Code.IndexOf("return 0;", StringComparison.Ordinal), "csharp"));
        Assert.Equal("public static class Calculator", DeclarationHeuristic.FindEnclosingDeclaration(text, Code.IndexOf("\n    \n", StringComparison.Ordinal) + 5, "csharp"));
    }

    [Fact]
    public void TheCaretLineItself_WhenTypingAHeader()
    {
        const string Code = "class C\n{\n    int Area(int r)\n}\n";
        var text = new StringDocumentText(Code);

        Assert.Equal("int Area(int r)", DeclarationHeuristic.FindEnclosingDeclaration(text, Code.IndexOf(')') + 1, "csharp"));
    }

    [Fact]
    public void Python_UsesIndentation()
    {
        const string Code = "class Shape:\n    def area(self):\n        total = 0\n        \n\ndef other():\n    pass\n";
        var text = new StringDocumentText(Code);
        var caret = Code.IndexOf("        \n", StringComparison.Ordinal) + 8;

        Assert.Equal("def area(self):", DeclarationHeuristic.FindEnclosingDeclaration(text, caret, "python"));
    }

    [Fact]
    public void TopLevelCode_HasNoEnclosingDeclaration()
    {
        const string Code = "using System;\n\nConsole.WriteLine(1);\n";
        var text = new StringDocumentText(Code);

        Assert.Null(DeclarationHeuristic.FindEnclosingDeclaration(text, Code.Length - 1, "csharp"));
    }
}
