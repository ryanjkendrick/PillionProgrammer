public sealed class ContentInspectorTests
{
    [Fact]
    public void PlainText_IsIncluded()
    {
        Assert.True(ContentInspector.Inspect("hello\nworld\n"u8).IsIncluded);
        Assert.True(ContentInspector.Inspect(ReadOnlySpan<byte>.Empty).IsIncluded);
    }

    [Fact]
    public void ANulByte_MeansBinary()
    {
        Assert.Equal(ExclusionReason.Binary, ContentInspector.Inspect([0x4D, 0x5A, 0x00, 0x03]).Reason);
    }

    [Theory]
    [InlineData("// <auto-generated/>", ExclusionReason.GeneratedHeader)]
    [InlineData("/* @generated */", ExclusionReason.GeneratedHeader)]
    [InlineData("// <autogenerated>", ExclusionReason.GeneratedHeader)]
    [InlineData("// Generated by the protocol buffer compiler.  DO NOT EDIT!", ExclusionReason.GeneratedHeader)]
    [InlineData("// Code generated by x. DO NOT EDIT.", ExclusionReason.GeneratedHeader)]
    [InlineData("// Code generated by hand", ExclusionReason.None)]
    [InlineData("// please do not edit this by hand", ExclusionReason.None)]
    [InlineData("// handwritten, generated nothing", ExclusionReason.None)]
    public void GeneratedHeaders_AreRecognised(string text, ExclusionReason expected)
    {
        Assert.Equal(expected, ContentInspector.Inspect(System.Text.Encoding.UTF8.GetBytes(text)).Reason);
    }

    [Fact]
    public void ANonexistentFile_IsUnreadable()
    {
        var decision = ContentInspector.Inspect(Path.Combine(Path.GetTempPath(), "pillion-missing-" + Guid.NewGuid().ToString("N")));

        Assert.Equal(ExclusionReason.Unreadable, decision.Reason);
    }
}

public sealed class PartitionResolverTests
{
    [Fact]
    public void AFile_BelongsToTheDeepestProject_ElseItsTopLevelFolder_ElseTheRoot()
    {
        using var temp = new TempDirectory();
        var resolver = new PartitionResolver(
            temp.Path,
            [
                new IndexedProject("App", temp.File("src/App")),
                new IndexedProject("App.Core", temp.File("src/App/Core")),
                IndexedProject.FromProjectFile(temp.File("tests/App.Tests/App.Tests.csproj")),
                new IndexedProject("Elsewhere", Path.Combine(Path.GetTempPath(), "somewhere-else")),
            ]);

        Assert.Equal("App", resolver.Resolve("src/App/Program.cs"));
        Assert.Equal("App.Core", resolver.Resolve("src/App/Core/Thing.cs"));
        Assert.Equal("App.Core", resolver.Resolve("src/app/core/deeper/Thing.cs"));
        Assert.Equal("App.Tests", resolver.Resolve("tests/App.Tests/UnitTests.cs"));
        Assert.Equal("src", resolver.Resolve("src/Other/Thing.cs"));
        Assert.Equal("docs", resolver.Resolve("docs/guide.md"));
        Assert.Equal(PartitionResolver.RootPartition, resolver.Resolve("README.md"));
        Assert.Equal("src", resolver.Resolve("src/AppExtra/Thing.cs"));
    }

    [Fact]
    public void AProjectAtTheRoot_OwnsEverythingNotInANestedProject()
    {
        using var temp = new TempDirectory();
        var resolver = new PartitionResolver(temp.Path, [new IndexedProject("Solo", temp.Path), new IndexedProject("Nested", temp.File("nested"))]);

        Assert.Equal("Solo", resolver.Resolve("README.md"));
        Assert.Equal("Solo", resolver.Resolve("src/a.cs"));
        Assert.Equal("Nested", resolver.Resolve("nested/b.cs"));
    }
}

public sealed class RepositoryRootsTests
{
    private static void MakeRepo(TempDirectory temp, string relative) => temp.MakeDirectory(relative + "/.git");

    [Fact]
    public void ASolutionAndItsProjects_CollapseToTheGitTopLevelDirectory()
    {
        using var temp = new TempDirectory();
        MakeRepo(temp, "repo");
        temp.Write("repo/App.sln");
        temp.Write("repo/src/App/App.csproj");
        temp.Write("repo/src/Lib/Lib.csproj");

        var roots = RepositoryRoots.Resolve([temp.File("repo/App.sln"), temp.File("repo/src/App/App.csproj"), temp.File("repo/src/Lib/Lib.csproj")]);

        var root = Assert.Single(roots);
        Assert.Equal(temp.File("repo"), root.Path);
        Assert.Equal(RepositoryRootKind.GitRepository, root.Kind);
        Assert.Equal(temp.File("repo/.git"), root.GitDirectory);
        Assert.True(root.IsGit);
    }

    [Fact]
    public void ASolutionSpanningTwoRepositories_YieldsTwoRoots()
    {
        using var temp = new TempDirectory();
        MakeRepo(temp, "one");
        MakeRepo(temp, "two");
        temp.Write("one/src/A/A.csproj");
        temp.Write("two/src/B/B.csproj");
        temp.Write("one/src/C/C.csproj");

        var roots = RepositoryRoots.Resolve([temp.File("one/src/A/A.csproj"), temp.File("two/src/B/B.csproj"), temp.File("one/src/C/C.csproj")]);

        Assert.Equal([temp.File("one"), temp.File("two")], roots.Select(r => r.Path));
    }

    [Fact]
    public void AnOpenedFolderInsideARepository_ResolvesToTheRepository()
    {
        using var temp = new TempDirectory();
        MakeRepo(temp, "repo");
        temp.MakeDirectory("repo/src/deep/er");

        var root = RepositoryRoots.ResolveOne(temp.File("repo/src/deep/er"));

        Assert.Equal(temp.File("repo"), root!.Path);
        Assert.Equal(RepositoryRootKind.GitRepository, root.Kind);
    }

    [Fact]
    public void AWorktreeGitFile_MakesItsFolderTheRoot_AndPointsAtTheRealGitDirectory()
    {
        using var temp = new TempDirectory();
        MakeRepo(temp, "main");
        temp.MakeDirectory("main/.git/worktrees/feature");
        temp.Write("feature-wt/.git", $"gitdir: {temp.File("main/.git/worktrees/feature").Replace('\\', '/')}\n");
        temp.Write("feature-wt/src/App/App.csproj");

        var roots = RepositoryRoots.Resolve([temp.File("feature-wt/src/App/App.csproj")]);

        var root = Assert.Single(roots);
        Assert.Equal(temp.File("feature-wt"), root.Path);
        Assert.Equal(RepositoryRootKind.GitWorktree, root.Kind);
        Assert.Equal(temp.File("main/.git/worktrees/feature"), root.GitDirectory);
    }

    [Fact]
    public void ARelativeGitDirInAGitFile_IsResolvedAgainstTheFolder_AndASubmoduleIsRecognised()
    {
        using var temp = new TempDirectory();
        MakeRepo(temp, "super");
        temp.MakeDirectory("super/.git/modules/lib");
        temp.Write("super/lib/.git", "gitdir: ../.git/modules/lib\n");
        temp.Write("super/lib/src/Lib.csproj");

        var roots = RepositoryRoots.Resolve([temp.File("super/lib/src/Lib.csproj"), temp.File("super/App.sln")]);

        Assert.Equal(2, roots.Count);
        var submodule = roots[0];
        Assert.Equal(temp.File("super/lib"), submodule.Path);
        Assert.Equal(RepositoryRootKind.GitSubmodule, submodule.Kind);
        Assert.Equal(temp.File("super/.git/modules/lib"), submodule.GitDirectory);
        Assert.Equal(temp.File("super"), roots[1].Path);
        Assert.Equal(RepositoryRootKind.GitRepository, roots[1].Kind);
    }

    [Fact]
    public void AGitFileWithoutAGitdirLine_StillMakesTheFolderARoot()
    {
        using var temp = new TempDirectory();
        temp.Write("odd/.git", "nonsense");
        temp.Write("odd/a.csproj");

        var root = Assert.Single(RepositoryRoots.Resolve([temp.File("odd/a.csproj")]));

        Assert.Equal(temp.File("odd"), root.Path);
        Assert.Equal(RepositoryRootKind.GitFile, root.Kind);
        Assert.Null(root.GitDirectory);
    }

    [Fact]
    public void WithoutGit_TheOpenedFolderIsTheRoot_AndProjectFoldersCollapseIntoTheSolutionFolder()
    {
        using var temp = new TempDirectory();
        temp.Write("plain/App.sln");
        temp.Write("plain/src/A/A.csproj");
        temp.Write("plain/src/B/B.csproj");
        temp.Write("elsewhere/C/C.csproj");

        var roots = RepositoryRoots.Resolve(
            [temp.File("plain/src/A/A.csproj"), temp.File("plain/App.sln"), temp.File("plain/src/B/B.csproj"), temp.File("elsewhere/C/C.csproj")]);

        Assert.Equal([temp.File("plain"), temp.File("elsewhere/C")], roots.Select(r => r.Path));
        Assert.All(roots, r => Assert.Equal(RepositoryRootKind.Folder, r.Kind));
        Assert.All(roots, r => Assert.Null(r.GitDirectory));
        Assert.All(roots, r => Assert.False(r.IsGit));
    }

    [Fact]
    public void AnOpenedFolderPath_IsUsedAsIs()
    {
        using var temp = new TempDirectory();
        temp.MakeDirectory("folder/sub");

        var root = Assert.Single(RepositoryRoots.Resolve([temp.File("folder") + Path.DirectorySeparatorChar]));

        Assert.Equal(temp.File("folder"), root.Path);
    }

    [Fact]
    public void ADuplicateOrMissingPath_IsHandled()
    {
        using var temp = new TempDirectory();
        MakeRepo(temp, "repo");
        temp.Write("repo/App.sln");

        var roots = RepositoryRoots.Resolve([temp.File("repo/App.sln"), temp.File("REPO/app.sln"), "", "   ", temp.File("repo/gone/Gone.csproj")]);

        Assert.Single(roots);
        Assert.Empty(RepositoryRoots.Resolve([]));
    }

    [Fact]
    public void TheNearestGitFolder_Wins()
    {
        using var temp = new TempDirectory();
        MakeRepo(temp, "outer");
        MakeRepo(temp, "outer/inner");
        temp.MakeDirectory("outer/inner/src");

        Assert.Equal(temp.File("outer/inner"), RepositoryRoots.FindGitRoot(temp.File("outer/inner/src"))!.Path);
        Assert.Equal(temp.File("outer"), RepositoryRoots.FindGitRoot(temp.File("outer"))!.Path);
    }
}
