using Pillion.Indexing.Discovery;

namespace Pillion.Indexing.Tests;

/// <summary>
/// The one-path classifier of work item 2.10 decides exactly as the scan does: every file of a tree that exercises the
/// rules gets the scan's decision (or, under an excluded folder, that folder's), and the by-name check the watcher uses
/// agrees wherever no disk access is needed.
/// </summary>
public sealed class PathClassifierTests
{
    private static TempDirectory Tree()
    {
        var temp = new TempDirectory();
        temp.Write("src/Program.cs", "class P {}");
        temp.Write("src/Generated.g.cs", "class G {}");
        temp.Write("src/Form.Designer.cs", "class F {}");
        temp.Write("src/bin/Debug/app.cs", "x");
        temp.Write("src/obj/project.assets.json", "{}");
        temp.Write("web/app.ts", "export {}");
        temp.Write("web/app.min.js", "x");
        temp.Write("web/node_modules/left-pad/index.js", "x");
        temp.Write("web/package-lock.json", "{}");
        temp.Write(".env", "KEY=1");
        temp.Write("config/appsettings.Production.json", "{}");
        temp.Write("logs/today.log", "x");
        temp.Write("logs/keep.log", "x");
        temp.Write(".gitignore", "logs/\n*.tmp\n");
        temp.Write("docs/.gitignore", "drafts/\n!important.tmp\n");
        temp.Write("docs/drafts/one.md", "x");
        temp.Write("docs/important.tmp", "x");
        temp.Write("docs/other.tmp", "x");
        temp.Write("docs/guide.md", "# guide");
        temp.Write(".pillionignore", "secret-stuff/\n");
        temp.Write("secret-stuff/notes.md", "x");
        temp.Write("vendor/lib.cs", "x");
        temp.Write("nested/.git/HEAD", "ref: refs/heads/main");
        temp.Write("nested/code.cs", "x");
        temp.Write("big/huge.txt", new string('x', 2048));
        temp.WriteBytes("assets/logo.dat", [1, 2, 0, 4]);
        temp.Write("gen/proto.cs", "// <auto-generated/>\nclass X {}");
        return temp;
    }

    private static ScanOptions Options => new() { ExcludePatterns = ["vendor/"], MaxFileBytes = 1024, MaxDegreeOfParallelism = 2 };

    [Fact]
    public async Task EveryFileOfATree_GetsTheScansDecision()
    {
        using var temp = Tree();
        var scanned = (await new RepositoryScanner(Options).ScanToListAsync(temp.Path)).ToDictionary(e => e.RelativePath, StringComparer.OrdinalIgnoreCase);
        var classifier = new PathClassifier(temp.Path, Options);

        var files = Directory.EnumerateFiles(temp.Path, "*", SearchOption.AllDirectories)
            .Select(f => Path.GetRelativePath(temp.Path, f).Replace('\\', '/'))
            .ToList();
        Assert.True(files.Count > 20);
        foreach (var file in files)
        {
            var entry = classifier.Classify(file);
            Assert.NotNull(entry);
            var expected = scanned.TryGetValue(file, out var direct)
                ? direct.Decision

                // Under a folder the scan excluded as a whole: the deepest such folder's decision.
                : scanned.Values.Where(e => e.IsDirectory && file.StartsWith(e.RelativePath + "/", StringComparison.OrdinalIgnoreCase))
                    .OrderBy(e => e.RelativePath.Length).First().Decision;
            Assert.True(expected.Reason == entry!.Decision.Reason, $"{file}: scan says {expected.Reason}, classifier says {entry.Decision.Reason}");
        }

        Assert.True(classifier.Classify("src/Program.cs")!.Decision.IsIncluded);
        Assert.Equal(Languages.CSharp, classifier.Classify("src/Program.cs")!.Language);
        Assert.Equal(ExclusionReason.NestedRepository, classifier.Classify("nested/code.cs")!.Decision.Reason);
        Assert.Equal(ExclusionReason.TooLarge, classifier.Classify("big/huge.txt")!.Decision.Reason);
        Assert.Equal(ExclusionReason.Binary, classifier.Classify("assets/logo.dat")!.Decision.Reason);
        Assert.Equal(ExclusionReason.GeneratedHeader, classifier.Classify("gen/proto.cs")!.Decision.Reason);
    }

    [Theory]
    [InlineData("src/bin/Debug/app.cs", ExclusionReason.BuiltIn)]
    [InlineData("src/obj/x.cs", ExclusionReason.BuiltIn)]
    [InlineData(".git/HEAD", ExclusionReason.BuiltIn)]
    [InlineData("web/node_modules/a/b/c.js", ExclusionReason.BuiltIn)]
    [InlineData("src/Generated.g.cs", ExclusionReason.GeneratedFile)]
    [InlineData("web/app.min.js", ExclusionReason.MinifiedFile)]
    [InlineData("web/package-lock.json", ExclusionReason.LockFile)]
    [InlineData(".env", ExclusionReason.SecretBearing)]
    [InlineData("logs/new.log", ExclusionReason.GitIgnore)]
    [InlineData("a/b/c.tmp", ExclusionReason.GitIgnore)]
    [InlineData("docs/drafts/two.md", ExclusionReason.GitIgnore)]
    [InlineData("secret-stuff/x.md", ExclusionReason.PillionIgnore)]
    [InlineData("vendor/lib.cs", ExclusionReason.UserExclude)]
    [InlineData("src/New.cs", ExclusionReason.None)]
    [InlineData("docs/important.tmp", ExclusionReason.None)]
    public void ByName_DecidesWithoutLookingAtTheFile_EvenWhenItDoesNotExist(string path, ExclusionReason reason)
    {
        using var temp = Tree();
        var classifier = new PathClassifier(temp.Path, Options);

        Assert.Equal(reason, classifier.ClassifyByName(path).Reason);
    }

    [Fact]
    public void Classify_ReturnsNullForAPathThatDoesNotExist_AndTheFolderForAFolder()
    {
        using var temp = Tree();
        var classifier = new PathClassifier(temp.Path, Options);

        Assert.Null(classifier.Classify("src/Gone.cs"));
        var folder = classifier.Classify("src");
        Assert.True(folder!.IsDirectory);
        Assert.True(folder.Decision.IsIncluded);
        Assert.Equal(ExclusionReason.BuiltIn, classifier.Classify("src/bin")!.Decision.Reason);
        Assert.Equal(ExclusionReason.NestedRepository, classifier.Classify("nested")!.Decision.Reason);
    }

    [Fact]
    public void AnIgnoreFileChange_IsSeenAfterInvalidate()
    {
        using var temp = Tree();
        var classifier = new PathClassifier(temp.Path, Options);
        Assert.True(classifier.ClassifyByName("docs/guide.md").IsIncluded);

        temp.Write("docs/.gitignore", "drafts/\n*.md\n");
        Assert.True(classifier.ClassifyByName("docs/guide.md").IsIncluded); // cached until told

        classifier.Invalidate();
        Assert.Equal(ExclusionReason.GitIgnore, classifier.ClassifyByName("docs/guide.md").Reason);
    }

    [Theory]
    [InlineData(".gitignore", true)]
    [InlineData("src/.gitignore", true)]
    [InlineData("src\\.GITIGNORE", true)]
    [InlineData(".pillionignore", true)]
    [InlineData("src/.pillionignore", false)]
    [InlineData("src/gitignore.cs", false)]
    public void IgnoreFiles_AreRecognised(string path, bool expected) => Assert.Equal(expected, PathClassifier.IsIgnoreFile(path));
}
